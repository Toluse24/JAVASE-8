class Switch2{
    public static void main(String args[]){

        int i;
        for (i=0; i<=4; i++){
            switch (i){
                case 0:
                case 1:
                case 2:
                    System.out.println("i is 0, 1 or 2");
                    break;
                case 3:
                    System.out.println("i is 4");
                    break;

            }
        }
    }
}
